import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import * as esbuild from 'esbuild';
import * as prettier from 'prettier';

const schemaPath = new URL('../src/context-snapshot.schema.json', import.meta.url);
const outputPath = new URL('../src/generated-schema-validator.ts', import.meta.url);
const outputFile = fileURLToPath(outputPath);
const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
const ajv = new Ajv({ allErrors: true, strict: true, code: { source: true, lines: true } });
const validate = ajv.compile(schema);
const bundled = await esbuild.build({
  stdin: {
    contents: standaloneCode(ajv, validate),
    resolveDir: fileURLToPath(new URL('..', import.meta.url)),
    sourcefile: 'generated-schema-validator.cjs',
    loader: 'js',
  },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  write: false,
});
const generated = await prettier.format(
  `// Generated by packages/model/scripts/generate-validator.mjs. Do not edit.\n// @ts-nocheck\n${bundled.outputFiles[0].text}\n`,
  {
    ...(await prettier.resolveConfig(outputFile)),
    filepath: outputFile,
  },
);

if (process.argv.includes('--check')) {
  let existing;
  try {
    existing = await readFile(outputPath, 'utf8');
  } catch {
    existing = '';
  }
  if (existing !== generated) {
    process.stderr.write(
      'Generated schema validator is stale. Run npm run generate --workspace @context-atlas/model.\n',
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated);
}
